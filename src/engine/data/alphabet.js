export const GLYPH_HEIGHT = 7;

export function hasGlyph(ch) {
  return Object.prototype.hasOwnProperty.call(F, ch.toUpperCase()) || Object.prototype.hasOwnProperty.call(F, ch);
}

export function glyph(ch) {
  return F[ch] ?? F[ch.toUpperCase()] ?? null;
}

/**
 * Render a string as a boolean pixel grid, one row per array entry.
 * @param {string} text
 * @param {{spacing?:number}} [opts]
 * @returns {boolean[][]} rows of booleans, height GLYPH_HEIGHT
 */
export function renderText(text, opts = {}) {
  const spacing = opts.spacing ?? 1;
  const chars = [];
  const src = String(text).toUpperCase();
  for (let i = 0; i < src.length; i++) {
    if (src[i] === '<' && src.slice(i, i + 2) === '<3') {
      chars.push(F['<3']);
      i++;
      continue;
    }
    const g = glyph(src[i]);
    if (g) chars.push(g);
  }
  if (!chars.length) return Array.from({ length: GLYPH_HEIGHT }, () => []);
  const rows = Array.from({ length: GLYPH_HEIGHT }, () => []);
  chars.forEach((g, idx) => {
    if (idx > 0) for (let r = 0; r < GLYPH_HEIGHT; r++) for (let s = 0; s < spacing; s++) rows[r].push(false);
    for (let r = 0; r < GLYPH_HEIGHT; r++) {
      for (const c of g[r]) rows[r].push(c === '#');
    }
  });
  return rows;
}

/** Width in knots that a string will occupy. */
export function textWidth(text, spacing = 1) {
  return renderText(text, { spacing })[0].length;
}

/** Every glyph the alphabet can knot. `<3` is a single two-character token. */
